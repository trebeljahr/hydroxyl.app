/**
 * Stage the 3D view's conformer worker into `packages/client/public/conformer/`.
 *
 * Two files land there, neither through the bundler:
 *
 *   conformer.worker.js      src/lib/conformer/worker.ts with OpenChemLib and
 *                            its force-field tables, bundled by esbuild
 *   THIRD-PARTY-NOTICES.txt  OpenChemLib's licence, which travels with it
 *
 * The same staging as RDKit's, for the same reasons (copy-rdkit.mjs has them
 * in full): a worker routed through Turbopack loses the export's subpath and
 * fails with an empty error message, and an esbuild bundle keeps the worker's
 * source typechecked and unit-tested.
 *
 * ONLY THE FORCE-FIELD TABLES ARE BUNDLED. OpenChemLib's resources.json is
 * 1.35 MB, most of it torsion statistics for the ConformerGenerator (which
 * the 3D view does not use; embed.ts says why) and toxicity predictors. The
 * `virtual:openchemlib-forcefield` module is that file filtered to the
 * `/resources/forcefield/` keys, about 0.2 MB. Bundled rather than fetched
 * beside the worker so the worker is one request and needs no base URL.
 */

import { createRequire } from "node:module";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import * as esbuild from "esbuild";

const require = createRequire(import.meta.url);
const here = path.dirname(fileURLToPath(import.meta.url));
const clientRoot = path.join(here, "..");
const outDir = path.join(clientRoot, "public", "conformer");

// Keep in step with FORCE_FIELD_RESOURCE_PREFIX in src/lib/conformer/embed.ts;
// embed.node.test.ts registers the same slice, so a mismatch fails there.
const FORCE_FIELD_RESOURCE_PREFIX = "/resources/forcefield/";

// The package exports no subpath for these; they sit beside its entry point.
const oclDist = path.dirname(require.resolve("openchemlib"));
const oclRoot = path.dirname(oclDist);
const version = JSON.parse(await readFile(path.join(oclRoot, "package.json"), "utf8")).version;
const allResources = JSON.parse(await readFile(path.join(oclDist, "resources.json"), "utf8"));
const forceField = Object.fromEntries(
  Object.entries(allResources).filter(([key]) => key.startsWith(FORCE_FIELD_RESOURCE_PREFIX)),
);
if (Object.keys(forceField).length === 0) {
  throw new Error(`openchemlib ${version}: no ${FORCE_FIELD_RESOURCE_PREFIX} keys in resources.json`);
}

await mkdir(outDir, { recursive: true });

await esbuild.build({
  entryPoints: [path.join(clientRoot, "src", "lib", "conformer", "worker.ts")],
  outfile: path.join(outDir, "conformer.worker.js"),
  bundle: true,
  // Classic, like the RDKit worker: Turbopack strips `{type:"module"}`.
  format: "iife",
  platform: "browser",
  target: "es2020",
  minify: true,
  legalComments: "none",
  logLevel: "warning",
  plugins: [
    {
      name: "openchemlib-forcefield",
      setup(build) {
        build.onResolve({ filter: /^virtual:openchemlib-forcefield$/ }, (args) => ({
          path: args.path,
          namespace: "openchemlib-forcefield",
        }));
        build.onLoad({ filter: /.*/, namespace: "openchemlib-forcefield" }, () => ({
          contents: JSON.stringify(forceField),
          loader: "json",
        }));
      },
    },
  ],
});

const licence = await readFile(path.join(oclRoot, "LICENSE"), "utf8");

await writeFile(
  path.join(outDir, "THIRD-PARTY-NOTICES.txt"),
  `Third-party notices for the files in this directory.

Generated by packages/client/scripts/copy-conformer.mjs. Do not edit by hand.

conformer.worker.js bundles openchemlib ${version} (OpenChemLib JS) and the
MMFF94 parameter tables from its resources.json.

===============================================================================
OpenChemLib — BSD 3-Clause. Verbatim copy of the LICENSE file shipped in
openchemlib ${version}.
===============================================================================

${licence.trimEnd()}
`,
);

console.log(`conformer: staged openchemlib ${version} into packages/client/public/conformer/`);
